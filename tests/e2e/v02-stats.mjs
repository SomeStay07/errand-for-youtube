import { join } from "node:path";
import { launch, reporter, consent, sleep, storage, closeWelcome, finish, messages, OUT, QUERY } from "./harness.mjs";

const SUMMARY = messages("en").M.errandsSummary.message.replace("$DONE$", "1").replace("$CLOSED$", "1");

const { check, save } = reporter();
const ctx = await launch({ name: "stats" });
const { context } = ctx;
await closeWelcome(ctx);
const today = () => ctx.worker.evaluate(() => chrome.storage.local.get(["stats", "errandLast"]).then((d) => ({ day: (d.stats || {})[globalThis.ErrandLib.dayKey(new Date())] || {}, last: d.errandLast })));

const ext = await context.newPage();
await ext.goto(`chrome-extension://${ctx.extId}/popup.html`);
const send = (m) => ext.evaluate((msg) => chrome.runtime.sendMessage(msg).catch(() => {}), m);
await send({ type: "errand", kind: "done", id: 111 });
await sleep(300);
await send({ type: "errand", kind: "done", id: 111 });
await sleep(300);
const s1 = await today();
check("B bg: done counted once per errand id", s1.day.done === 1, JSON.stringify(s1));
await send({ type: "errand", kind: "done", id: "abc" });
await sleep(300);
check("B bg: non-number id ignored", (await today()).day.done === 1);
const closer = async (msg) => {
  const p = await context.newPage();
  await p.goto(`chrome-extension://${ctx.extId}/popup.html`);
  p.evaluate((m) => chrome.runtime.sendMessage(m).catch(() => {}), msg).catch(() => {});
  await p.waitForEvent("close", { timeout: 3000 }).catch(() => {});
  await sleep(300);
  return p.isClosed();
};
const c1 = await closer({ type: "close-tab", errand: 222 });
check("B bg: close-tab for an errand not yet done → not counted, tab closed", (await today()).day.closed === undefined && c1, JSON.stringify(await today()));
const c2 = await closer({ type: "close-tab", errand: 111 });
const c3 = await closer({ type: "close-tab", errand: 111 });
const s2 = await today();
check("B bg: close-tab counted once for the done errand", s2.day.closed === 1 && c2 && c3, JSON.stringify(s2));
await closer({ type: "close-tab", errand: null });
check("B bg: close-tab without errand not counted", (await today()).day.closed === 1);
await ext.reload();
await sleep(600);
const summary = await ext.evaluate(() => ({ hidden: document.getElementById("week").hidden, text: document.getElementById("summary").textContent }));
await ext.screenshot({ path: join(OUT, "B-popup-stats.png"), fullPage: true });
check(`B popup shows '${SUMMARY}'`, !summary.hidden && summary.text === SUMMARY, summary);

await ctx.worker.evaluate(() => chrome.storage.local.remove(["stats", "errandLast"]));
const yt = context.pages().find((p) => !p.url().startsWith("chrome-extension://")) || (await context.newPage());
await yt.goto("https://www.youtube.com/", { waitUntil: "domcontentloaded" });
await consent(yt);
await sleep(3000);
await yt.locator("#er-intent input").click();
await yt.keyboard.type(QUERY);
await yt.keyboard.press("Enter");
await yt.waitForURL(/results/, { timeout: 20000 });
await sleep(4000);
const { intent } = await storage(ctx, "intent");
await yt.locator('ytd-video-renderer a#thumbnail[href^="/watch"], yt-lockup-view-model a[href^="/watch"]').first().click();
await yt.waitForURL(/watch/, { timeout: 20000 });
await sleep(6000);
const fire = () => yt.evaluate(() => {
  const v = document.querySelector("video.html5-main-video");
  if (!v) return "no video element";
  v.dispatchEvent(new Event("ended"));
  return "dispatched";
});
const env = await yt.evaluate(() => ({ video: Boolean(document.querySelector("video.html5-main-video")), ad: document.getElementById("movie_player")?.classList.contains("ad-showing"), duration: document.querySelector("video.html5-main-video")?.duration }));
console.log("player env:", JSON.stringify(env));
const r1 = await fire();
await sleep(1200);
const prompt = await yt.evaluate(() => ({ shown: Boolean(document.getElementById("er-end")), text: document.querySelector("#er-end p")?.textContent, buttons: [...document.querySelectorAll("#er-end button")].map((b) => b.textContent) }));
await yt.screenshot({ path: join(OUT, "B-end-prompt-synthetic.png") });
const t1 = await today();
check("B content (synthetic 'ended'): done +1 with intent.ts as id, end prompt shown", r1 === "dispatched" && t1.day.done === 1 && t1.last?.done === intent?.ts && prompt.shown, `${r1}; ${JSON.stringify(t1)}; prompt=${JSON.stringify(prompt)}`);
await fire();
await sleep(800);
check("B content: second 'ended' same errand → still 1", (await today()).day.done === 1);

await ctx.worker.evaluate(() => chrome.storage.local.set({ pausedUntil: Date.now() + 60000 }));
await sleep(1000);
await yt.evaluate(() => document.getElementById("er-end")?.remove());
await ctx.worker.evaluate(() => chrome.storage.local.set({ errandLast: { done: null, closed: null } }));
await fire();
await sleep(1000);
const paused = { prompt: await yt.evaluate(() => Boolean(document.getElementById("er-end"))), day: (await today()).day };
check("B content: during pause no prompt, no counting", !paused.prompt && paused.day.done === 1, paused);
await ctx.worker.evaluate((ts) => chrome.storage.local.set({ errandLast: { done: ts, closed: null } }).then(() => chrome.storage.local.remove("pausedUntil")), intent.ts);
await sleep(1000);
await fire();
await sleep(1000);
const closedTab = yt.waitForEvent("close", { timeout: 4000 }).then(() => true).catch(() => false);
const promptVisible = await yt.evaluate(() => Boolean(document.querySelector("#er-end button.er-primary")?.checkVisibility()));
console.log("prompt visible on screen (player overlaid by bot check):", promptVisible);
await yt.evaluate(() => document.querySelector("#er-end button.er-primary").click());
const wasClosed = await closedTab;
await sleep(800);
const t2 = await today();
check("B content: Close tab in prompt closes the tab and counts closed once", wasClosed && t2.day.closed === 1 && t2.day.done === 1, `closed=${wasClosed} ${JSON.stringify(t2)}`);
await ext.reload();
await sleep(600);
check(`B popup after content flow: '${SUMMARY}'`, (await ext.locator("#summary").textContent()) === SUMMARY && !(await ext.locator("#week").isHidden()));
check("B incognito not counted", null, "Playwright persistent context cannot open an incognito tab with the extension allowed; check by hand");

await finish(ctx, check);
save("B-stats-results.json");
await context.close();
